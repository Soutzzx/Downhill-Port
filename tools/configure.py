#!/usr/bin/env python3
"""Generate build.ninja: rebuild SCUS_971.77 from splat asm + decompiled C, then check it.

  python tools/configure.py && python -m ninja
  trial build (tools/try_func.py does this):
  python tools/configure.py --build-dir build-try/x --extra-unit "LINE" && python -m ninja -f build-try/x/build.ninja
  NONMATCHING build (behaviour-equivalent C for unmatched functions, docs/WORKER.md):
  python tools/configure.py --nonmatching && python -m ninja -f build-nonmatching/build.ninja
    Every unit gets -DNONMATCHING; pieces are placed at their retail address or, if an earlier
    piece grew, right after it, so the image links but is not expected to match (no check step;
    `python tools/check_image.py build-nonmatching/dhd.elf` lists the differences).

Inputs (asm/ and assets/ are regenerated by `python tools/split.py`):
  asm/nonmatchings/text/*.s   one file per retail function
  asm/data/*.s                data/rodata/except table/sdata/sbss/bss
  assets/vutext.bin           VU microcode (binary)
  src/**/*.{c,cpp}            C/C++ translation units. The first line declares the unit:
                                /* UNIT START END [SECTION=START:END ...] [-flag ...] */
                              hex vram, END exclusive. START..END is the unit's .text; each
                              SECTION=range (.data .rodata .gcc_except_table .sdata .sbss .bss)
                              is data the unit's object provides instead of splat's asm;
                              -flags are added to the unit's compiler flags. One marker per
                              file, so parallel work never edits a shared list. Rerun
                              configure after adding a source file.
Every piece (asm run, C object, data piece) is linked at its absolute retail address, so a
piece that comes out the wrong size fails loudly instead of shifting everything after it.
A C unit must cover its range exactly; functions in it not decompiled yet use INCLUDE_ASM.
"""
import argparse, json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, 'tools'))
import toolchain
from asmprep import prep

TEXT_ASM = 'asm/nonmatchings/text'
# CreateProcess (ninja on Windows) wants a native absolute path for executables.
BU = os.path.join(ROOT, 'tools', 'compilers', 'ps2dev-binutils', 'mips64r5900el-ps2-elf-')
SECTIONS = [  # name, vram, splat asm file (None = special)
    ('.text', 0x10A000, None),
    ('.vutext', 0x263BC0, None),
    ('.data', 0x26DD00, 'asm/data/data.data.s'),
    ('.rodata', 0x288880, 'asm/data/rodata.rodata.s'),
    ('.gcc_except_table', 0x29BF80, 'asm/data/gcc_except_table.gcc_except_table.s'),
    ('.sdata', 0x29C100, 'asm/data/sdata.sdata.s'),
    ('.sbss', 0x29DD00, 'asm/data/sbss.sbss.s'),
    ('.bss', 0x29E580, 'asm/data/bss.bss.s'),
]
SIZES = {'.text': 0x159BC0, '.vutext': 0xA140, '.data': 0x1AB70, '.rodata': 0x136D8,
         '.gcc_except_table': 0x148, '.sdata': 0x1BF0, '.sbss': 0x848, '.bss': 0x601E80}
TEXT_END = 0x263BC0
# Region starts (crt0 | game | libgcc | engine | sdk), same map as tools/queue.py.
REGIONS = [(0x10A000, 'crt0'), (0x10A208, 'game'), (0x1FC000, 'libgcc'), (0x201000, 'engine'),
           (0x243000, 'sdk')]
REGION_CUTS = [a for a, _ in REGIONS[1:]]
DATA_SECTIONS = ('.data', '.rodata', '.gcc_except_table', '.sdata', '.sbss', '.bss')
# Input sections a C object may contribute to each output section (gcc 2.95 MIPS names).
C_INPUTS = {'.text': ['.text'], '.data': ['.data'], '.rodata': ['.rodata', '.rdata'],
            '.gcc_except_table': ['.gcc_except_table'], '.sdata': ['.sdata', '.lit4', '.lit8'],
            '.sbss': ['.sbss', '.scommon'], '.bss': ['.bss', 'COMMON']}
VRAM = re.compile(r'/\*\s*[0-9A-Fa-f]+\s+([0-9A-Fa-f]{8})\s')
BLOCK_VRAM = re.compile(r'/\*\s*(?:[0-9A-Fa-f]+\s+)?([0-9A-Fa-f]{8})(?:\s|\*)')


def write_if_changed(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    if os.path.exists(path) and open(path, newline='').read() == text:
        return
    with open(path, 'w', newline='\n') as f:
        f.write(text)


def handwritten():
    """Start addresses of game/engine functions splat marks as handwritten assembly (instructions
    gcc never emits). They can't be decompiled; each gets its own asm object so the progress
    report can count them separately ('handwritten' category)."""
    lo, hi = REGIONS[1][0], REGIONS[-1][0]
    listed = _name_list('handwritten.txt')  # read and judged by hand (the marker alone isn't proof)
    out = set()
    for v, f in text_functions():
        if lo <= v < hi:
            with open(os.path.join(ROOT, TEXT_ASM, f)) as fh:
                if 'Handwritten function' in fh.read(300) or f[:-2] in listed:
                    out.add(v)
    return out


def _name_list(name):
    path = os.path.join(ROOT, 'config', name)
    return {l.split()[0] for l in open(path) if l.strip() and not l.startswith('#')} if os.path.exists(path) else set()


def remnants():
    """Start addresses of game/engine dead-strip leftovers (the same rule as tools/queue.py): 4-byte
    pieces, pieces without any jr/j, and config/remnants.txt. They stay asm and are no function of the
    source; like handwritten ones each is its own asm object, category 'remnant' in the report."""
    lo, hi = REGIONS[1][0], REGIONS[-1][0]
    listed = _name_list('remnants.txt')
    out = set()
    for v, f in text_functions():
        if lo <= v < hi:
            text = open(os.path.join(ROOT, TEXT_ASM, f)).read()
            m = re.search(r'nonmatching\s+\S+,\s*(0x[0-9A-Fa-f]+)', text)
            if (m and int(m.group(1), 16) <= 4) or not re.search(r'\*/\s+(jr|j)\s', text) or f[:-2] in listed:
                out.add(v)
    return out


def text_functions():
    """[(vram, filename)] for every function .s, in address order."""
    out = []
    for f in os.listdir(os.path.join(ROOT, TEXT_ASM)):
        with open(os.path.join(ROOT, TEXT_ASM, f)) as fh:
            m = VRAM.search(fh.read())
        out.append((int(m.group(1), 16), f))
    return sorted(out)


def parse_unit(line):
    """`START END SRC [SECTION=A:B ...] [-flag ...]` -> (start, end, src, {sec: (a, b)}, [flags])"""
    f = line.split('#')[0].split()
    extra, flags = {}, []
    for x in f[3:]:
        if x.startswith('-'):
            flags.append(x)
            continue
        sec, rng = x.split('=')
        a, b = rng.split(':')
        assert sec in DATA_SECTIONS, 'unknown section %s in units.txt' % sec
        extra[sec] = (int(a, 16), int(b, 16))
    return (int(f[0], 16), int(f[1], 16), f[2], extra, flags)


UNIT_MARK = re.compile(r'^/\*\s*UNIT\s+(.*?)\s*\*/')


def unit_marker(path):
    """The `/* UNIT START END [SECTION=A:B ...] [-flag ...] */` first line of a source, or None."""
    with open(os.path.join(ROOT, path)) as f:
        m = UNIT_MARK.match(f.readline())
    if not m:
        return None
    f = m.group(1).split()
    return parse_unit(' '.join(f[:2] + [path] + f[2:]))


def sources():
    out = []
    for d, _, files in os.walk(os.path.join(ROOT, 'src')):
        for f in files:
            if f.endswith(('.c', '.cc', '.cpp')):
                out.append(os.path.relpath(os.path.join(d, f), ROOT).replace('\\', '/'))
    return sorted(out)


def units():
    """Units from the UNIT markers in src/: [(start, end, src, {section: (a, b)}, [flags])].
    A source without a marker is not linked (e.g. a header-like helper or work in progress)."""
    us = [u for u in (unit_marker(p) for p in sources()) if u]
    us.sort()
    for a, b in zip(us, us[1:]):
        assert a[1] <= b[0], 'overlapping units %s %s' % (a[2], b[2])
    return us


def split_data(text, cuts):
    """Split a splat data .s at symbol boundaries (cuts: sorted vram addresses).
    Returns (header_lines, [(start_vram, lines)]); a new piece starts at each cut."""
    lines = text.split('\n')
    hdr_end = next(i for i, l in enumerate(lines)
                   if l.startswith('nonmatching') or l.startswith('.align'))
    header, body = lines[:hdr_end], lines[hdr_end:]
    # a block is [.align] nonmatching / dlabel / data lines
    starts = [i - 1 if i and body[i - 1].startswith('.align') else i
              for i, l in enumerate(body) if l.startswith('nonmatching')]
    blocks = []
    for k, i in enumerate(starts):
        chunk = body[i:starts[k + 1] if k + 1 < len(starts) else len(body)]
        m = next((BLOCK_VRAM.search(l) for l in chunk if BLOCK_VRAM.search(l)), None)
        blocks.append((int(m.group(1), 16) if m else None, chunk))
    pieces, cur, remaining = [], None, list(cuts)
    for v, chunk in blocks:
        if v is not None and remaining and v >= remaining[0]:
            assert v == remaining[0], \
                'cut at %#x is not on a symbol boundary (next symbol %#x)' % (remaining[0], v)
            remaining.pop(0)
            cur = None
        if cur is None:
            cur = (v, [])
            pieces.append(cur)
        cur[1].extend(chunk)
    assert not remaining or remaining == [blocks[-1][0]], \
        'cuts past the end of the section: %s' % [hex(x) for x in remaining]
    return header, pieces


RODATA_INC = re.compile(r'INCLUDE_RODATA\(\s*"build/rodata"\s*,\s*(\w+)\s*\)')


def write_rodata_blocks(us):
    """A unit can keep retail .rodata it doesn't decompile (e.g. jump tables of its INCLUDE_ASM
    functions, inside its own .rodata range) with INCLUDE_RODATA("build/rodata", SYMBOL): one
    splat block, written here from asm/data, so no extracted data is committed."""
    want = set()
    for _, _, src, _, _ in us:
        want |= set(RODATA_INC.findall(open(os.path.join(ROOT, src), encoding='utf-8', errors='replace').read()))
    if not want:
        return
    src = next(s for n, _, s in SECTIONS if n == '.rodata')
    body = prep(open(os.path.join(ROOT, src)).read()).split('\n')
    starts = [i - 1 if i and body[i - 1].startswith('.align') else i
              for i, l in enumerate(body) if l.startswith('nonmatching')]
    for k, i in enumerate(starts):
        chunk = body[i:starts[k + 1] if k + 1 < len(starts) else len(body)]
        name = next(l.split()[1].rstrip(',') for l in chunk if l.startswith('nonmatching'))
        if name in want:
            write_if_changed(os.path.join(ROOT, 'build', 'rodata', name + '.s'), '\n'.join(chunk) + '\n')
            want.discard(name)
    assert not want, 'INCLUDE_RODATA of unknown .rodata symbols: %s' % sorted(want)


def align_to_org(lines, base):
    """.align is relative to the section start, and would also raise the piece's section
    alignment so ld moves a piece cut at an unaligned address. Replace it with .org to the
    retail address of the next data line (from splat's comment), relative to the piece."""
    out = []
    for i, l in enumerate(lines):
        if l.startswith('.align'):
            nxt = next((BLOCK_VRAM.search(x) for x in lines[i + 1:] if BLOCK_VRAM.search(x)), None)
            if nxt is None:
                continue  # trailing .align with nothing after it
            out.append('.org 0x%X' % (int(nxt.group(1), 16) - base))
        else:
            out.append(l)
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--build-dir', default='build')
    ap.add_argument('--extra-unit', action='append', default=[],
                    help='"START END SRC [SECTION=A:B] [-flag]"; replaces units it overlaps')
    ap.add_argument('--nonmatching', action='store_true',
                    help='compile units with -DNONMATCHING into build-nonmatching/ (links, no check)')
    a = ap.parse_args()
    nm = a.nonmatching
    if nm and a.build_dir == 'build':
        a.build_dir = 'build-nonmatching'
    B = a.build_dir.replace('\\', '/').rstrip('/')
    default = B == 'build' and not a.extra_unit and not nm
    toolchain.check()
    funcs = text_functions()
    us = units()
    main_units = set((s, e, src, tuple(sorted(x.items())), tuple(f)) for s, e, src, x, f in us)
    # Trial builds reuse the main build's objects for everything they share with it (identical
    # generated asm, unchanged C units), so a trial compiles only its candidate. Requires the
    # main build to be current (`python -m ninja`); keep it current before building this one.
    reuse = B != 'build' and os.path.exists(os.path.join(ROOT, 'build', 'check.ok'))
    for line in a.extra_unit:
        new = parse_unit(line)
        us = [u for u in us if u[1] <= new[0] or u[0] >= new[1]] + [new]
    us.sort()
    starts = {v for v, _ in funcs}
    for s, e, src, _, _ in us:
        assert s in starts and (e in starts or e == TEXT_END), 'unit %s bounds not on functions' % src
    write_rodata_blocks(us)

    # Off Windows (toolchain.WINE) the assembler runs under Wine and Python is python3.
    asm = ' '.join(toolchain.exe(BU + 'as.exe'))
    py = 'python3' if toolchain.WINE else 'python'
    n = ['ninja_required_version = 1.10',
         'builddir = %s' % B,  # .ninja_log/.ninja_deps per build dir: parallel trials are safe
         'rule as', '  command = %s -EL -march=r5900 -mabi=eabi -G8 -no-pad-sections '
         '-I include -o $out $in' % asm, '  description = AS $out',
         'rule cc', '  command = %s tools/sncc.py $in $out $flags' % py, '  description = CC $out',
         '  depfile = $out.d', '  deps = gcc',
         # objects go through a response file: hundreds of paths overflow Windows' 32K command line
         'rule ld', '  command = %s tools/link.py $script $map $out @$out.rsp' % py,
         '  rspfile = $out.rsp', '  rspfile_content = $in',
         '  description = LD $out',
         'rule check', '  command = %s tools/check_image.py --stamp $out $in' % py,
         '  description = CHECK $in',
         'rule configure', '  command = %s tools/configure.py' % py, '  generator = 1',
         '  description = CONFIGURE', '']
    place = {name: [] for name, _, _ in SECTIONS}  # section -> [(vram, obj, [input sections])]
    objs = []

    def asm_obj(path, text, implicit=''):
        if reuse:  # trial build: an identical piece the main build already assembled
            main = 'build' + path[len(B):]
            mo = main[:-2] + '.o'
            mp = os.path.join(ROOT, main)
            if (os.path.exists(os.path.join(ROOT, mo)) and os.path.exists(mp)
                    and open(mp, newline='').read() == text):
                objs.append(mo)
                return mo
        write_if_changed(os.path.join(ROOT, path), text)
        o = path[:-2] + '.o'
        n.append('build %s: as %s%s' % (o, path, implicit))
        objs.append(o)
        return o

    # .text: runs of asm functions between C units
    run, ui = [], 0
    hand = handwritten() | remnants()  # each alone in its own asm object

    def flush():
        if run:
            body = ['.include "macro.inc"', '.set noat', '.set noreorder', '.section .text, "ax"']
            body += [prep(open(os.path.join(ROOT, TEXT_ASM, f)).read()) for _, f in run]
            o = asm_obj('%s/asm/text_%08X.s' % (B, run[0][0]), '\n'.join(body) + '\n')
            place['.text'].append((run[0][0], o, ['.text']))
            del run[:]
    for v, f in funcs:
        while ui < len(us) and v >= us[ui][1]:
            ui += 1
        if ui < len(us) and us[ui][0] <= v < us[ui][1]:
            flush()
            continue
        if run and (any(run[-1][0] < cut <= v for cut in REGION_CUTS)
                    or v in hand or run[-1][0] in hand):
            flush()  # one region per asm object (handwritten functions alone), so progress
            # reports can categorise it
        run.append((v, f))
    flush()
    expected = []  # objdiff "target" objects: each C unit's retail asm (tools/report.py)
    for s, e, src, extra, flags in us:
        o = '%s/%s.o' % (B, src)
        mo = 'build/%s.o' % src
        if (reuse and not nm and (s, e, src, tuple(sorted(extra.items())), tuple(flags)) in main_units
                and os.path.exists(os.path.join(ROOT, mo))
                and os.path.getmtime(os.path.join(ROOT, mo)) >= os.path.getmtime(os.path.join(ROOT, src))):
            o = mo  # unchanged unit: the main build's object
        else:
            n.append('build %s: cc %s | tools/sncc.py tools/toolchain.py tools/asm_sn.py' % (o, src))
            if flags or nm:
                n.append('  flags = %s' % ' '.join(flags + ['-DNONMATCHING'] * nm))
        objs.append(o)
        place['.text'].append((s, o, C_INPUTS['.text']))
        for sec, (lo, hi) in extra.items():
            place[sec].append((lo, o, C_INPUTS[sec]))
        body = ['.include "macro.inc"', '.set noat', '.set noreorder', '.section .text, "ax"']
        body += [prep(open(os.path.join(ROOT, TEXT_ASM, f)).read()) for v, f in funcs if s <= v < e]
        es = '%s/expected/%s.s' % (B, src)
        write_if_changed(os.path.join(ROOT, es), '\n'.join(body) + '\n')
        n.append('build %s.o: as %s' % (es[:-2], es))
        expected.append(es[:-2] + '.o')

    o = asm_obj(B + '/asm/vutext.s', '.section .vutext, "ax"\n.incbin "assets/vutext.bin"\n',
                ' | assets/vutext.bin')
    place['.vutext'].append((TEXT_END, o, ['.vutext']))

    # data sections: splat asm, with holes where a C unit provides the data
    for name, vram, src in SECTIONS:
        if not src:
            continue
        text = prep(open(os.path.join(ROOT, src)).read())
        if name in ('.sbss', '.bss'):
            # splat fills the gap up to the next section with an "unreferenced pad"; for
            # NOBITS that gap is just the next section's alignment, which ld reproduces.
            text = re.sub(r'\nnonmatching (D_\w+), 0x\w+\n\n/\* Automatically generated and '
                          r'unreferenced pad \*/\ndlabel \1\n[^\n]*\.space [^\n]*\n*$', '\n', text)
        owned = sorted(r for _, _, _, x, _ in us for sec, r in x.items() if sec == name)
        cuts = sorted({c for lo, hi in owned for c in (lo, hi)})
        header, pieces = split_data(text, cuts)
        stem = os.path.basename(src)[:-2].split('.')[0]
        for pv, plines in pieces:
            if any(lo <= pv < hi for lo, hi in owned):
                continue
            o = asm_obj('%s/asm/data/%s_%08X.s' % (B, stem, pv),
                        '\n'.join(header + align_to_org(plines, pv)) + '\n')
            place[name].append((pv, o, [name]))

    ld = ['ENTRY(_start)',
          'INCLUDE build/undefined_syms_auto.txt',   # written by splat
          'INCLUDE build/undefined_funcs_auto.txt',
          'INCLUDE %s/aliases.ld' % B,              # C++ names, written by tools/link.py
          'SECTIONS', '{']
    for name, vram, src in SECTIONS:
        # NONMATCHING: a piece that grew pushes the rest (and later sections) up instead of failing
        addr = 'MAX(0x%X, ALIGN(16))' % vram if nm and name != '.text' else '0x%X' % vram
        ld.append('    %s %s%s :' % (name, addr, ' (NOLOAD)' if name in ('.sbss', '.bss') else ''))
        ld.append('    {')
        prev = None
        for pv, o, ins in sorted(place[name]):
            if nm:
                ld.append('        . = MAX(., 0x%X);' % (pv - vram))
            else:
                if prev:
                    ld.append('        ASSERT(. <= 0x%X, "%s is too big: overlaps the piece at 0x%X");'
                              % (pv - vram, prev, pv))
                ld.append('        . = 0x%X;' % (pv - vram))
            ld.append('        %s(%s)' % (o, ' '.join(ins)))
            prev = o
        if not nm:
            ld.append('        ASSERT(. <= 0x%X, "%s ends past retail %s end");' % (
                SIZES[name], prev, name))
        ld.append('    }')
    ld += ['    _gp = 0x2A40F0;',
           # No catch-all discard: an unexpected section from a C object becomes an orphan
           # that ld places somewhere, and check_image then fails.
           '    /DISCARD/ : { *(.reginfo) *(.MIPS.abiflags) *(.pdr) *(.mdebug*) *(.comment)'
           ' *(.gnu.attributes) *(.note*) }',
           '}']
    write_if_changed(os.path.join(ROOT, B, 'dhd.ld'), '\n'.join(ld) + '\n')
    n.append('build %s/dhd.elf: ld %s | %s/dhd.ld tools/link.py' % (B, ' '.join(objs), B))
    n.append('  script = %s/dhd.ld' % B)
    n.append('  map = %s/dhd.map' % B)
    if not nm:
        n.append('build %s/check.ok: check %s/dhd.elf | iso/SCUS_971.77 tools/check_image.py' % (B, B))
    if default:
        # any source's UNIT marker can change the layout; new sources need a manual rerun
        n.append('build build.ninja: configure | tools/configure.py tools/asmprep.py %s'
                 % ' '.join(sources()))
    n.append('build expected: phony %s' % ' '.join(expected))
    n.append('default %s/%s' % (B, 'dhd.elf' if nm else 'check.ok'))
    with open(os.path.join(ROOT, B, 'units.json'), 'w', newline='\n') as f:  # for report.py
        json.dump({'text_pieces': [(pv, o) for pv, o, _ in sorted(place['.text'])],
                   'units': [(s, e, src, '%s/expected/%s.o' % (B, src)) for s, e, src, _, _ in us]},
                  f, indent=0)
    # Always rewrite: ninja reruns the generator until build.ninja is newer than its inputs.
    ninja_file = 'build.ninja' if default else B + '/build.ninja'
    os.makedirs(os.path.join(ROOT, B), exist_ok=True)
    with open(os.path.join(ROOT, ninja_file), 'w', newline='\n') as f:
        f.write('\n'.join(n) + '\n')
    print('configured %s: %d functions, %d text pieces, %d C units, %d objects' % (
        ninja_file, len(funcs), len(place['.text']), len(us), len(objs)))


if __name__ == '__main__':
    main()
